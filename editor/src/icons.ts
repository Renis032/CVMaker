export function iconSvg(name: string, strokeWidth = 2): string {
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] ?? ''}</svg>`;
}

/** The icon for a contact line: email, phone, LinkedIn, GitHub, a web address or the location. */
export function contactIcon(text: string, isLocation = false): string {
  const t = text.trim().toLowerCase();
  if (isLocation) return 'pin';
  if (/^\S+@\S+\.\S+$/.test(t)) return 'mail';
  if (/^\+?[\d\s()-]{7,}$/.test(t)) return 'phone';
  if (t.includes('linkedin')) return 'linkedin';
  if (t.includes('github')) return 'github';
  if (/^(https?:\/\/)?[\w-]+(\.[\w-]+)+(\/\S*)?$/.test(t)) return 'globe';
  return 'dot';
}
